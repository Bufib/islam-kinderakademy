create or replace function public.save_multiple_choice_quiz(
  target_lesson_id bigint,
  quiz_title text,
  quiz_description text,
  required_passing_percent integer,
  publish_quiz boolean,
  question_definitions jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  saved_quiz_id bigint;
  saved_question_id bigint;
  saved_option_id bigint;
  correct_option_id bigint;
  question_definition jsonb;
  option_definition jsonb;
  question_position integer;
  option_position integer;
  correct_option_count integer;
begin
  if not public.is_academy_staff() then
    raise exception 'Academy staff role required';
  end if;

  if not exists (select 1 from public.lessons where id = target_lesson_id) then
    raise exception 'Lesson not found';
  end if;

  if coalesce(nullif(trim(quiz_title), ''), '') = '' then
    raise exception 'Quiz title required';
  end if;

  if required_passing_percent not between 0 and 100 then
    raise exception 'Passing percent must be between 0 and 100';
  end if;

  if coalesce(jsonb_typeof(question_definitions), 'null') <> 'array'
    or jsonb_array_length(question_definitions) = 0 then
    raise exception 'At least one quiz question is required';
  end if;

  insert into public.lesson_quizzes (
    lesson_id,
    title,
    description,
    passing_percent,
    is_published
  )
  values (
    target_lesson_id,
    trim(quiz_title),
    nullif(trim(quiz_description), ''),
    required_passing_percent,
    publish_quiz
  )
  on conflict (lesson_id) do update
  set
    title = excluded.title,
    description = excluded.description,
    passing_percent = excluded.passing_percent,
    is_published = excluded.is_published
  returning id into saved_quiz_id;

  -- Bei strukturellen Aenderungen beginnen Versuche und Fortschritt neu.
  delete from public.quiz_attempts where quiz_id = saved_quiz_id;
  delete from public.child_lesson_progress where lesson_id = target_lesson_id;
  delete from public.quiz_questions where quiz_id = saved_quiz_id;

  question_position := 0;
  for question_definition in
    select value from jsonb_array_elements(question_definitions)
  loop
    if coalesce(nullif(trim(question_definition ->> 'question_text'), ''), '') = '' then
      raise exception 'Every quiz question needs text';
    end if;

    if coalesce(jsonb_typeof(question_definition -> 'options'), 'null') <> 'array'
      or jsonb_array_length(question_definition -> 'options') < 2 then
      raise exception 'Every quiz question needs at least two options';
    end if;

    select count(*)
    into correct_option_count
    from jsonb_array_elements(question_definition -> 'options') as option_row(value)
    where coalesce((option_row.value ->> 'is_correct')::boolean, false);

    if correct_option_count <> 1 then
      raise exception 'Every quiz question needs exactly one correct option';
    end if;

    insert into public.quiz_questions (quiz_id, question_text, position)
    values (saved_quiz_id, trim(question_definition ->> 'question_text'), question_position)
    returning id into saved_question_id;

    option_position := 0;
    correct_option_id := null;

    for option_definition in
      select value from jsonb_array_elements(question_definition -> 'options')
    loop
      if coalesce(nullif(trim(option_definition ->> 'option_text'), ''), '') = '' then
        raise exception 'Every quiz option needs text';
      end if;

      insert into public.quiz_options (question_id, option_text, position)
      values (saved_question_id, trim(option_definition ->> 'option_text'), option_position)
      returning id into saved_option_id;

      if coalesce((option_definition ->> 'is_correct')::boolean, false) then
        correct_option_id := saved_option_id;
      end if;

      option_position := option_position + 1;
    end loop;

    insert into public.quiz_answer_keys (question_id, correct_option_id, explanation)
    values (
      saved_question_id,
      correct_option_id,
      nullif(trim(question_definition ->> 'explanation'), '')
    );

    question_position := question_position + 1;
  end loop;

  return saved_quiz_id;
end;
$$;

create or replace function public.submit_multiple_choice_quiz(
  target_child_id bigint,
  target_quiz_id bigint,
  submitted_answers jsonb
)
returns table (
  attempt_id bigint,
  correct_answers integer,
  total_questions integer,
  score_percent integer,
  passed boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  quiz_lesson_id bigint;
  required_percent integer;
  created_attempt_id bigint;
  question_count integer;
  valid_answer_count integer;
  correct_count integer;
  calculated_percent integer;
  did_pass boolean;
begin
  if not public.owns_child(target_child_id) and not public.is_academy_staff() then
    raise exception 'Child access required';
  end if;

  select quiz.lesson_id, quiz.passing_percent
  into quiz_lesson_id, required_percent
  from public.lesson_quizzes as quiz
  join public.lessons as lesson on lesson.id = quiz.lesson_id
  join public.learning_journeys as journey on journey.id = lesson.learning_journey_id
  join public.academy_years as academy_year on academy_year.id = journey.academy_year_id
  where quiz.id = target_quiz_id
    and quiz.is_published
    and lesson.status = 'published'
    and journey.is_published
    and academy_year.is_active;

  if quiz_lesson_id is null then
    raise exception 'Published quiz not found';
  end if;

  if coalesce(jsonb_typeof(submitted_answers), 'null') <> 'array' then
    raise exception 'Quiz answers must be an array';
  end if;

  select count(*)
  into question_count
  from public.quiz_questions
  where quiz_id = target_quiz_id;

  if question_count = 0 then
    raise exception 'Quiz has no questions';
  end if;

  select count(*)
  into valid_answer_count
  from (
    select distinct answer.question_id
    from jsonb_to_recordset(submitted_answers)
      as answer(question_id bigint, option_id bigint)
    join public.quiz_questions as question
      on question.id = answer.question_id
      and question.quiz_id = target_quiz_id
    join public.quiz_options as quiz_option
      on quiz_option.id = answer.option_id
      and quiz_option.question_id = question.id
  ) as valid_answers;

  if valid_answer_count <> question_count
    or jsonb_array_length(submitted_answers) <> question_count then
    raise exception 'Every quiz question must have one valid answer';
  end if;

  insert into public.quiz_attempts (
    child_id,
    quiz_id,
    correct_answers,
    total_questions,
    score_percent,
    passed
  )
  values (target_child_id, target_quiz_id, 0, question_count, 0, false)
  returning id into created_attempt_id;

  insert into public.quiz_attempt_answers (
    attempt_id,
    question_id,
    selected_option_id,
    is_correct
  )
  select
    created_attempt_id,
    answer.question_id,
    answer.option_id,
    answer.option_id = answer_key.correct_option_id
  from jsonb_to_recordset(submitted_answers)
    as answer(question_id bigint, option_id bigint)
  join public.quiz_questions as question
    on question.id = answer.question_id
    and question.quiz_id = target_quiz_id
  join public.quiz_options as quiz_option
    on quiz_option.id = answer.option_id
    and quiz_option.question_id = question.id
  join public.quiz_answer_keys as answer_key
    on answer_key.question_id = question.id;

  select count(*) filter (where answer.is_correct)
  into correct_count
  from public.quiz_attempt_answers as answer
  where answer.attempt_id = created_attempt_id;

  calculated_percent := round((correct_count::numeric / question_count::numeric) * 100)::integer;
  did_pass := calculated_percent >= required_percent;

  update public.quiz_attempts
  set
    correct_answers = correct_count,
    score_percent = calculated_percent,
    passed = did_pass
  where id = created_attempt_id;

  insert into public.child_lesson_progress as progress (
    child_id,
    lesson_id,
    status,
    progress_percent,
    last_opened_at,
    completed_at
  )
  values (
    target_child_id,
    quiz_lesson_id,
    case when did_pass then 'completed' else 'in_progress' end,
    calculated_percent,
    now()::timestamp without time zone,
    case when did_pass then now()::timestamp without time zone else null end
  )
  on conflict (child_id, lesson_id) do update
  set
    status = case
      when progress.status = 'completed' or excluded.status = 'completed' then 'completed'
      else 'in_progress'
    end,
    progress_percent = greatest(progress.progress_percent, excluded.progress_percent),
    last_opened_at = excluded.last_opened_at,
    completed_at = coalesce(progress.completed_at, excluded.completed_at);

  return query
  select
    created_attempt_id,
    correct_count,
    question_count,
    calculated_percent,
    did_pass;
end;
$$;

