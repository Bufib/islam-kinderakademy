-- Neuer Lektionsablauf: Einstiegstext, geplanter Live-Unterricht und
-- eigenständiges Multiple-Choice-Quiz mit serverseitiger Auswertung.

alter table public.lessons
add column if not exists intro_text text not null default '';

update public.lessons as lesson
set intro_text = coalesce(
  (
    select nullif(trim(step.content ->> 'text'), '')
    from public.lesson_steps as step
    where step.lesson_id = lesson.id
      and step.step_type = 'start'
    order by step.position, step.id
    limit 1
  ),
  nullif(trim(lesson.description), ''),
  ''
)
where lesson.intro_text = '';

create table public.lesson_quizzes (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null unique references public.lessons (id) on delete cascade,
  title text not null,
  description text,
  passing_percent smallint not null default 70 check (passing_percent between 0 and 100),
  is_published boolean not null default false,
  created_at timestamp without time zone not null default now()
);

create table public.quiz_questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.lesson_quizzes (id) on delete cascade,
  question_text text not null,
  position integer not null default 0 check (position >= 0),
  created_at timestamp without time zone not null default now(),
  unique (quiz_id, position)
);

create table public.quiz_options (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.quiz_questions (id) on delete cascade,
  option_text text not null,
  position integer not null default 0 check (position >= 0),
  created_at timestamp without time zone not null default now(),
  unique (question_id, position),
  unique (id, question_id)
);

-- Die richtige Antwort liegt absichtlich getrennt von den sichtbaren Optionen.
-- Dadurch können Kinder die Lösung nicht über die normale Datenabfrage auslesen.
create table public.quiz_answer_keys (
  id bigint generated by default as identity primary key,
  question_id bigint not null unique references public.quiz_questions (id) on delete cascade,
  correct_option_id bigint not null,
  explanation text,
  created_at timestamp without time zone not null default now(),
  foreign key (correct_option_id, question_id)
    references public.quiz_options (id, question_id)
    on delete cascade
);

create table public.quiz_attempts (
  id bigint generated by default as identity primary key,
  child_id bigint not null references public.children (id) on delete cascade,
  quiz_id bigint not null references public.lesson_quizzes (id) on delete cascade,
  correct_answers integer not null check (correct_answers >= 0),
  total_questions integer not null check (total_questions > 0),
  score_percent smallint not null check (score_percent between 0 and 100),
  passed boolean not null default false,
  submitted_at timestamp without time zone not null default now(),
  created_at timestamp without time zone not null default now()
);

create table public.quiz_attempt_answers (
  id bigint generated by default as identity primary key,
  attempt_id bigint not null references public.quiz_attempts (id) on delete cascade,
  question_id bigint not null references public.quiz_questions (id) on delete cascade,
  selected_option_id bigint not null,
  is_correct boolean not null,
  created_at timestamp without time zone not null default now(),
  unique (attempt_id, question_id),
  foreign key (selected_option_id, question_id)
    references public.quiz_options (id, question_id)
    on delete cascade
);

create index lesson_quizzes_lesson_id_idx on public.lesson_quizzes (lesson_id);
create index quiz_questions_quiz_id_idx on public.quiz_questions (quiz_id);
create index quiz_options_question_id_idx on public.quiz_options (question_id);
create index quiz_answer_keys_correct_option_id_idx on public.quiz_answer_keys (correct_option_id);
create index quiz_attempts_child_id_idx on public.quiz_attempts (child_id);
create index quiz_attempts_quiz_id_idx on public.quiz_attempts (quiz_id);
create index quiz_attempt_answers_attempt_id_idx on public.quiz_attempt_answers (attempt_id);
create index quiz_attempt_answers_question_id_idx on public.quiz_attempt_answers (question_id);
create index quiz_attempt_answers_selected_option_id_idx on public.quiz_attempt_answers (selected_option_id);

