-- Wiederverwendbare, RLS-sichere Zugriffshelfer.
create or replace function public.current_profile_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select p.id
  from public.profiles p
  where p.auth_user_id = (select auth.uid())
  limit 1
$$;

create or replace function public.has_account_role(required_role text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_roles ur
    where ur.profile_id = public.current_profile_id()
      and ur.role::text = required_role
  )
$$;

create or replace function public.is_academy_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_roles ur
    where ur.profile_id = public.current_profile_id()
      and ur.role::text in ('teacher', 'admin')
  )
$$;

create or replace function public.owns_child(target_child_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.children c
    where c.id = target_child_id
      and c.parent_profile_id = public.current_profile_id()
  )
$$;

create or replace function public.can_access_group(target_group_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_academy_staff()
    or exists (
      select 1
      from public.group_members gm
      join public.children c on c.id = gm.child_id
      where gm.group_id = target_group_id
        and c.parent_profile_id = public.current_profile_id()
    )
$$;
